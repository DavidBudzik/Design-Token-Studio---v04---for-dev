import { Token, TokenGroup } from '@/types/token';
import { 
  ExportFormat, 
  JSONExport, 
  FigmaTokensExport, 
  CSSVariablesExport, 
  SCSSMapsExport,
  ExportOptions 
} from '@/types/export';

export function exportTokens(
  tokens: Token[], 
  groups: TokenGroup[], 
  options: ExportOptions
): string {
  switch (options.format) {
    case 'json':
      return exportAsJSON(tokens, groups, options);
    case 'figma-tokens':
      return exportAsFigmaTokens(tokens, groups, options);
    case 'css-variables':
      return exportAsCSSVariables(tokens, options);
    case 'scss-maps':
      return exportAsSCSSMaps(tokens, groups, options);
    default:
      throw new Error(`Unsupported export format: ${options.format}`);
  }
}

function exportAsJSON(tokens: Token[], groups: TokenGroup[], options: ExportOptions): string {
  const jsonExport: JSONExport = {
    themeName: 'Design Token Studio Theme',
    description: 'Exported from Design Token Studio v4.0',
    version: '1.0.0',
    exportedAt: new Date().toISOString(),
    tokens: tokens,
  };

  if (options.includeMetadata) {
    jsonExport.metadata = {
      totalTokens: tokens.length,
      categories: [...new Set(tokens.map(t => t.category))],
      lastModified: new Date().toISOString(),
    };
  }

  return options.minify 
    ? JSON.stringify(jsonExport) 
    : JSON.stringify(jsonExport, null, 2);
}

function exportAsFigmaTokens(tokens: Token[], groups: TokenGroup[], options: ExportOptions): string {
  const figmaExport: FigmaTokensExport = {};

  tokens.forEach(token => {
    const category = token.category.toLowerCase();
    if (!figmaExport[category]) {
      figmaExport[category] = {};
    }

    const tokenName = options.prefix ? `${options.prefix}-${token.name}` : token.name;
    
    figmaExport[category][tokenName] = {
      value: token.value,
      type: mapTokenTypeToFigma(token.type),
      ...(token.description && { description: token.description }),
    };
  });

  return options.minify 
    ? JSON.stringify(figmaExport) 
    : JSON.stringify(figmaExport, null, 2);
}

function exportAsCSSVariables(tokens: Token[], options: ExportOptions): string {
  const cssVars: string[] = [':root {'];
  
  tokens.forEach(token => {
    const varName = `--${options.prefix || ''}${token.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`;
    cssVars.push(`  ${varName}: ${token.value};`);
  });
  
  cssVars.push('}');
  
  if (options.includeMetadata) {
    cssVars.unshift(`/* Generated by Design Token Studio v4.0 on ${new Date().toISOString()} */`);
    cssVars.unshift(`/* Total tokens: ${tokens.length} */`);
  }
  
  return cssVars.join('\n');
}

function exportAsSCSSMaps(tokens: Token[], groups: TokenGroup[], options: ExportOptions): string {
  const scssMaps: string[] = [];
  
  if (options.includeMetadata) {
    scssMaps.push(`// Generated by Design Token Studio v4.0 on ${new Date().toISOString()}`);
    scssMaps.push(`// Total tokens: ${tokens.length}\n`);
  }

  // Group tokens by category
  const tokensByCategory = tokens.reduce((acc, token) => {
    const category = token.category.toLowerCase();
    if (!acc[category]) acc[category] = [];
    acc[category].push(token);
    return acc;
  }, {} as Record<string, Token[]>);

  // Create SCSS maps for each category
  Object.entries(tokensByCategory).forEach(([category, categoryTokens]) => {
    const mapName = `$${options.prefix || ''}${category}-tokens`;
    scssMaps.push(`${mapName}: (`);
    
    categoryTokens.forEach((token, index) => {
      const tokenName = token.name.toLowerCase().replace(/[^a-z0-9]/g, '-');
      const isLast = index === categoryTokens.length - 1;
      scssMaps.push(`  '${tokenName}': ${token.value}${isLast ? '' : ','}`);
    });
    
    scssMaps.push(`);\n`);
  });

  return scssMaps.join('\n');
}

function mapTokenTypeToFigma(type: string): string {
  const typeMap: Record<string, string> = {
    color: 'color',
    spacing: 'spacing',
    typography: 'typography',
    borderRadius: 'borderRadius',
    shadow: 'boxShadow',
    gradient: 'gradient',
  };
  
  return typeMap[type] || 'other';
}

export function downloadFile(content: string, filename: string, mimeType: string = 'application/json') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function getFileExtension(format: ExportFormat): string {
  switch (format) {
    case 'json':
    case 'figma-tokens':
      return '.json';
    case 'css-variables':
      return '.css';
    case 'scss-maps':
      return '.scss';
    default:
      return '.txt';
  }
}

export function getMimeType(format: ExportFormat): string {
  switch (format) {
    case 'json':
    case 'figma-tokens':
      return 'application/json';
    case 'css-variables':
      return 'text/css';
    case 'scss-maps':
      return 'text/x-scss';
    default:
      return 'text/plain';
  }
}